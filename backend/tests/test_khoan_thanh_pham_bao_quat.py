def _tien(d) -> float:
    _n, _ma_so, ma, tc, nhom, sl, _dg, _tt = d
    return _may_tinh(ma, nhom, sl, tc)


@pytest.mark.parametrize("d", DONG, ids=[f"dòng {x[0]} {x[1]}" for x in DONG])
def test_tung_dong_so_khop(d):
    dong, _ma_so, _ma, _tc, _nhom, _sl, dg, tt = d
    if dong in SO_LOAI:
        assert tt is None and _tien(d) == pytest.approx(d[5] * dg)
    else:
        assert _tien(d) == pytest.approx(tt, abs=0.6)


def test_tong_tung_nhom_khop_bang_chia():
    for nhom, tong_so in BANG_CHIA.items():
        tong = sum(_tien(d) for d in DONG if d[4] == nhom and d[0] not in SO_LOAI)
        tong += sum(t for _n, ng, t in GIO if ng == nhom)
        assert tong == pytest.approx(tong_so, abs=1), nhom
    assert sum(BANG_CHIA.values()) == pytest.approx(145_819_631.47, abs=1)


def test_tuy_chon_gop_ra_dung_gia_ma_cu():
    nhom = "Thuận+ Vi+Thúy"
    # Kiểm phẩm tờ in: thường 30, trên 70cm 70 (mã cũ KIN / KIL).
    assert _may_tinh("KI", nhom, 1_000, {}) == pytest.approx(30_000)
    assert _may_tinh("KI", nhom, 1_000, {"tren_70cm": 1}) == pytest.approx(70_000)
    # Quấn keo: một đầu 70, hai đầu 140 (mã cũ Q1D / Q2D).
    assert _may_tinh("QK", nhom, 1_000, {}) == pytest.approx(70_000)
    assert _may_tinh("QK", nhom, 1_000, {"hai_dau": 1}) == pytest.approx(140_000)
    # Dán chip 2 con: sổ 130 đ/sản phẩm = 2 con × giá DC.
    assert _may_tinh("DC", nhom, 2_000, {}) == pytest.approx(1_000 * 130)
