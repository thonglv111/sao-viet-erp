def test_tung_dong_so_khop(d):
    dong, _ma, _nhom, sl, dg, tt, canh, _lan, _tha = d
    if dong in SO_LOAI:
        assert tt is None and _tien(d) == pytest.approx(sl * dg)
    else:
        assert _tien(d) == pytest.approx(tt + (canh or 0), abs=0.6)


